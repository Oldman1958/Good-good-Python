"""
Подвиг 5.
(Для учебных целей).
На вход программе подается строка.
Необходимо ее прочитать и в ней заменить кириллические символы на соответствующие латинские обозначения
(без учета регистра букв), а все остальные символы - на символ дефиса (-).
Для этого в программе уже объявлен словарь (см. листинг):

t = {'ё': 'yo', 'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ж': 'zh',
     'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p',
     'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c', 'ч': 'ch', 'ш': 'sh',
     'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'}

Используя его, примените функцию map, которая бы выдавала преобразованные фрагменты для входной строки.
На основе этой функции сформируйте строку,
состоящую из преобразованных фрагментов (фрагменты в строке должны идти друг за другом без пробелов).
Отобразите результат на экране.
"""

t = {'ё': 'yo', 'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ж': 'zh',
     'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p',
     'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c', 'ч': 'ch', 'ш': 'sh',
     'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'}

# Читаем входную строку
input_string = input()


# Функция для преобразования одного символа
def transform_char(char):
    # Приводим символ к нижнему регистру для соответствия ключам словаря
    lower_char = char.lower()
    # Если символ есть в словаре — возвращаем его замену
    if lower_char in t:
        return t[lower_char]
    # Иначе возвращаем дефис
    else:
        return '-'


# Применяем функцию transform_char к каждому символу строки с помощью map
transformed_chars = map(transform_char, input_string)

# Объединяем все преобразованные фрагменты в одну строку без пробелов
result_string = ''.join(transformed_chars)

# Выводим результат на экран
print(result_string)
