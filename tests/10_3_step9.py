"""
Значимый подвиг 7.
В программе инициализируется двумерное игровое поле размером N x N (N - натуральное число читается из входного потока),
представленное в виде вложенного списка:

P = [[0] * N for i in range(N)]

Требуется расставить на поле P случайным образом M = 10 единиц (целочисленных) так,
чтобы они не соприкасались друг с другом (то есть, вокруг каждой единицы должны быть нули, либо граница поля).

P.S. Поле на экран выводить не нужно (вообще ничего не нужно выводить), только сформировать.

"""

import random

# установка "зерна" датчика случайных чисел, чтобы получались одни и те же случайные величины
random.seed(1)
# начальная инициализация поля (переменные P и N не менять, единицы записывать в список P)
N = int(input())
P = [[0] * N for i in range(N)]

# здесь продолжайте программу
M = 10 #  Количество единиц, которые нужно расставить


def can_place_unit(row, col):
    """Проверяем, можно ли поставить единицу в ячейку (row, col)."""
    # Проверяем все 8 соседних клеток
    for drow in (-1, 0, 1):
        for dcol in (-1, 0, 1):
            if drow == 0 and dcol == 0:
                continue  # Пропускаем саму ячейку
            r, c = row + drow, col + dcol
            # Проверяем границы поля
            if 0 <= r < N and 0 <= c < N:
                if P[r][c] == 1:
                    return False  # В соседней клетке уже есть единица
    return True


placed = 0  # Количество уже расставленных единиц
attempts = 0  # Счётчик попыток (защита от бесконечного цикла)
max_attempts = N * N * 10  # Максимальное число попыток

while placed < M and attempts < max_attempts:
    row = random.randint(0, N - 1)
    col = random.randint(0, N - 1)

    if P[row][col] == 0 and can_place_unit(row, col):
        P[row][col] = 1
        placed += 1

    attempts += 1

# Если не удалось расставить все единицы, выводим предупреждение
if placed < M:
    print(f"Предупреждение: удалось расставить только {placed} единиц из {M}.")

# Код ниже только для проверки расстановки. Не отправлять
for i in range(N):
    for j in range(N):
        print(P[i][j], end=' ')
    print()


