"""
Подвиг 4.
Продолжите программу, в которой нужно объявить функцию с именем check_phone
и следующими параметрами (порядок следования важен):

phone - строка с номером телефона; только позиционные аргументы;
format_phone="8(xxx)xxx-xx-xx" - строка с проверяемым форматом номера телефона; только позиционные аргументы;
format_symbol='x' - форматный символ для произвольной цифры; принимает позиционные и именованные аргументы.

Функция check_phone должна проверять корректность записи номера телефона phone в соответствии с форматом,
указанном в параметре format_phone.
Формат телефонного номера format_phone содержит специальный символ (по умолчанию 'x'),
который соответствует произвольной цифре от 0 до 9.
Этот символ задается параметром format_symbol и изначально равен 'x'.
Если номер телефона phone полностью соответствует заданному формату format_symbol,
то функция check_phone должна возвращать булево значение True, а иначе False.

Например:

res1 = check_phone("8(945)221-61-62") # True
res2 = check_phone("8(945)221-5007") # False
res3 = check_phone("+7(945)221-5007", "+7(xxx)xxx-xxxx") # True
res4 = check_phone("+7(903)703-06-11", "+7(***)***-**-**", format_symbol='*') # True


Вызовите функцию check_phone для проверки следующего номера телефона:

phone_number = input()

на соответствие формата: +7(***)*** ****

Результат сохраните в переменной result.
"""

# здесь объявляйте функцию
def check_phone(phone, format_phone="8(xxx)xxx-xx-xx", /, format_symbol='x'):
    # Если длины строки номера и формата не совпадают, сразу возвращаем False
    if len(phone) != len(format_phone):
        return False

    # Перебираем символы строки номера и соответствующего формата одновременно
    for p_char, f_char in zip(phone, format_phone):
        if f_char == format_symbol:
            # Если текущий символ формата — это форматный символ (например, 'x' или '*'),
            # то соответствующий символ номера должен быть цифрой
            if not p_char.isdigit():
                return False
        else:
            # Если символ формата не является форматным символом,
            # он должен точно совпадать с соответствующим символом номера
            if p_char != f_char:
                return False

    # Если все проверки пройдены, возвращаем True
    return True

phone_number = input()

# здесь продолжайте программу

result = check_phone(phone_number, "+7(***)*** ****", format_symbol='*')