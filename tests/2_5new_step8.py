"""
Подвиг 8. В программе выполняется чтение координат (x0, y0) и (x1, y1) двух радиус-векторов:

x0, y0, x1, y1 = map(float, input().split())

Необходимо вычислить острый угол alfa между ними по формуле:

cos(alpha) = (x0⋅x1+y0⋅y1) / (((x0**2 + y0**2)**0.5) * ((x1**2 + y1**2))**0.5)

alpha = arccos(cos(alpha))

Результирующий угол в градусах сохраните в переменной alpha с округлением до десятых с помощью функции round().

P.S. На экран ничего выводить не нужно.
P.P.S. Содрал рещение в ИИ. Надоело искать клопов в своем коде...
"""

import math

# Чтение координат радиус‑векторов
x0, y0, x1, y1 = map(float, input().split())

# Вычисление скалярного произведения векторов
dot_product = x0 * x1 + y0 * y1

# Вычисление длин (норм) векторов
norm_v0 = math.sqrt(x0**2 + y0**2)
norm_v1 = math.sqrt(x1**2 + y1**2)

# Вычисление косинуса угла по формуле
cos_alpha = dot_product / (norm_v0 * norm_v1)

# Ограничение значения cos_alpha диапазоном [-1, 1] для предотвращения ошибок в arccos
cos_alpha = max(-1.0, min(1.0, cos_alpha))

# Вычисление угла в радианах, затем перевод в градусы
alpha_rad = math.acos(cos_alpha)
alpha_deg = math.degrees(alpha_rad)

# Округление до десятых и сохранение в переменную alpha
alpha = round(alpha_deg, 1)
