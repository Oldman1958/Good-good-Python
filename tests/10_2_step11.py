"""
Подвиг 9.
На вход программе подается целое десятичное число.
Прочитайте его и, используя битовые операции, проверьте, включен ли 5-й или 1-й биты введенного числа.
Если включен хотя бы один из этих битов, то выведите слово "ДА", иначе - слово "НЕТ".
"""

# Читаем целое число из входного потока
num = int(input())

# Создаём маски для 5-го и 1-го битов
mask_5 = 1 << 5
mask_1 = 1 << 1

# Проверяем, включены ли оба бита
bit_5_set = (num & mask_5) != 0
bit_1_set = (num & mask_1) != 0

# Если оба бита включены, выводим "ДА", иначе — "НЕТ"
print("ДА" if bit_5_set or bit_1_set else "НЕТ")
