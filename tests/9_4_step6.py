"""
Подвиг 4.
Саша и Галя коллекционируют монетки.
Каждый из них решил записать номиналы монеток из своей коллекции. Получились две последовательности.
Эти последовательности чисел (номиналов) поступают на вход программе в виде двух строк из целых чисел,
записанных через пробел.
Необходимо их прочитать и выделить значения, присутствующие в обоих списках, а затем, оставить среди них только четные.
Результат вывести на экран в виде строки полученных чисел в порядке их возрастания через пробел.

При реализации программы используйте функцию filter и кое-что еще (для упрощения программы), подумайте что.
"""


# Читаем входные данные и преобразуем в списки целых чисел
sasha = list(map(int, input().split()))
galya = list(map(int, input().split()))

# Находим пересечение множеств (общие номиналы)
common = set(sasha) & set(galya)

# Фильтруем чётные числа с помощью filter() и lambda-функции
even_common = filter(lambda x: x % 2 == 0, common)

# Сортируем результат и выводим через пробел
print(*sorted(even_common))
