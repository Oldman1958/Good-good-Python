"""
Подвиг 6.
На вход программе поступает список товаров в виде строк формата:

название_1:цена_1
...
название_N:цена_N

В программе уже реализовано считывание всех этих строк и сохранение в списке lst_in:

lst_in = list(map(str.strip, sys.stdin.readlines()))


Необходимо преобразовать этот список в словарь, ключами которого выступают цены (целые числа),
а значениями - соответствующие названия товаров.
Также необходимо написать функцию, которая бы принимала на входе словарь указанного формата
и возвращала список из наименований трех наиболее дешевых товаров.

Вызовите эту функцию и отобразите на экране полученный список в порядке возрастания цены в одну строчку через пробел.
"""

import sys

# считывание списка из входного потока
lst_in = list(map(str.strip, sys.stdin.readlines()))

# здесь продолжайте программу (используйте список строк lst_in)

# Преобразуем список строк в словарь: цена (ключ) -> название товара (значение)
# Используем генератор словаря: разбиваем каждую строку по ':', преобразуем цену в int
goods_dict = {int(item.split(':')[1]): item.split(':')[0] for item in lst_in}


def get_cheapest_goods(goods_dict, n=3):
    """
    Функция возвращает список из n наименований самых дешёвых товаров.

    Параметры:
    goods_dict — словарь вида {цена: название}
    n — количество товаров для возврата (по умолчанию 3)

    Возвращает:
    Список названий товаров, отсортированных по возрастанию цены
    """
    # Сортируем словарь по ключам (ценам) и берём первые n элементов
    sorted_items = sorted(goods_dict.items())
    # Извлекаем названия товаров (значения) из отсортированных пар
    cheapest_names = [name for price, name in sorted_items[:n]]
    return cheapest_names


# Вызываем функцию для получения трёх самых дешёвых товаров
result = get_cheapest_goods(goods_dict)

# Выводим результат в одну строку через пробел
print(' '.join(result))
