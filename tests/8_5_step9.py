"""
Подвиг 7.
Откройте файловый поток fp для чтения данных из файла с именем 'persons.dat' с кодировкой UTF-8,
который расположен в подкаталоге stuff относительно рабочего каталога.
В каждой строке этого файла записаны сотрудники в формате:

Имя Отчество Фамилия

Определите номер строки, в которой присутствует имя Сергей с фамилией Балакирев (отчество может быть любым).
Гарантируется, что такая строка в файле единственная, либо отсутствует.
Если такой строки нет, то номер должен быть равен нулю.
Результат (номер строки) сохраните в переменной num_person.

Не забудьте закрыть файловый поток после работы с ним.

P.S. На экран ничего выводить не нужно.
"""

fp = open('stuff/persons.dat', encoding='utf-8')
num_person = 0  # Инициализируем переменную: если строка не найдена, останется 0
# Перебираем строки файла с нумерацией (счёт начинается с 1)
for line_number, line in enumerate(fp, start=1):
    # Убираем лишние пробелы и переносы строк в конце строки
    cleaned_line = line.strip()

    # Разделяем строку на части (имя, отчество, фамилия)
    parts = cleaned_line.split()

    # Проверяем, что в строке есть как минимум 3 элемента
    if len(parts) >= 3:
        name = parts[0]  # Первый элемент — имя
        surname = parts[2]  # Третий элемент — фамилия

        # Проверяем условие: имя Сергей и фамилия Балакирев
        if name == 'Сергей' and surname == 'Балакирев':
            num_person = line_number
            break  # Так как строка единственная, прерываем поиск

fp.close()