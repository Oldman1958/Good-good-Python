"""
Подвиг 7.
На вход программе подается зашифрованное слово.
Шифрование кодов символов этого слова было проведено с помощью битовой операции XOR с ключом key=123.
То есть, каждый символ был преобразован по алгоритму:

x = ord(x) ^ key

Здесь ord - функция, возвращающая код символа x.
Прочитайте слово из входного потока и расшифруйте его.
Выведите на экран результат расшифровки.

P. S. Подсказка: для преобразования кода в символ используйте функцию chr.
"""

key = 123

# Читаем зашифрованное слово из входного потока
encrypted_word = input().strip()

# Расшифровываем каждый символ: преобразуем в код, применяем XOR с ключом, затем обратно в символ
decrypted_chars = []
for char in encrypted_word:
    # Получаем код зашифрованного символа
    encrypted_code = ord(char)
    # Расшифровываем код с помощью XOR с ключом
    original_code = encrypted_code ^ key
    # Преобразуем код обратно в символ
    original_char = chr(original_code)
    # Добавляем расшифрованный символ в список
    decrypted_chars.append(original_char)

# Объединяем символы в строку и выводим результат
decrypted_word = ''.join(decrypted_chars)
print(decrypted_word)
