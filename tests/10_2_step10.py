"""
Подвиг 8.
На вход программе подается целое десятичное число.
Прочитайте его и, используя битовые операции, проверьте, включен ли 6-й и 3-й биты введенного числа.
Если они оба включены, то выведите слово "ДА", иначе - слово "НЕТ".
"""

# Читаем целое число из входного потока
num = int(input())

# Создаём маски для 3-го и 6-го битов
mask_3 = 1 << 3  # 2^3 = 8
mask_6 = 1 << 6  # 2^6 = 64

# Проверяем, включены ли оба бита
bit_3_set = (num & mask_3) != 0
bit_6_set = (num & mask_6) != 0

# Если оба бита включены, выводим "ДА", иначе — "НЕТ"
print("ДА" if bit_3_set and bit_6_set else "НЕТ")

