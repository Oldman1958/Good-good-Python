"""
Подвиг 2.
На вход программе подается неравномерная таблица целых чисел.
В программе уже реализовано считывание ее строк  и сохранение в списке lst_in:

lst_in = list(map(str.strip, sys.stdin.readlines()))

С помощью функции zip необходимо выравнить эту таблицу, приведя ее к прямоугольному виду,
отбросив выходящие элементы в строках. Вывести результат на экран в виде такой же таблицы чисел.
В конце строк при выводе пробелов быть не должно.
"""

import sys

# считывание списка из входного потока
lst_in = list(map(str.strip, sys.stdin.readlines()))

# здесь продолжайте программу (используйте список строк lst_in)

# Преобразуем каждую строку в список целых чисел
table = [list(map(int, row.split())) for row in lst_in]

# Выравниваем таблицу с помощью zip: *table распаковывает списки, zip группирует по позициям
aligned_table = list(zip(*table))

# Транспонируем обратно: zip(*aligned_table) возвращает строки исходной ориентации
# (после первого zip строки стали столбцами, нужно вернуть их в строки)
result_rows = zip(*aligned_table)

# Выводим каждую строку: преобразуем числа в строки и соединяем через пробел
for row in result_rows:
    print(' '.join(map(str, row)))

