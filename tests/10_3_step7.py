"""
 На вход программе подается таблица целых чисел, записанных через пробел.
 В программе уже реализовано чтение ее строк:

lst_in = list(map(str.strip, sys.stdin.readlines()))

Необходимо преобразовать список строк lst_in в двумерный список чисел.
Затем, в полученном списке (таблице) перемешать столбцы, используя функции shuffle и zip.
Результат вывести на экран (также в виде таблицы). При выводе в конце строк не должно быть пробелов.
"""

import sys
import random
# установка "зерна" датчика случайных чисел, чтобы получались одни и те же случайные величины
random.seed(1)

# считывание списка из входного потока
lst_in = list(map(str.strip, sys.stdin.readlines()))

# здесь продолжайте программу

# Преобразуем строки в двумерный список чисел
table = [list(map(int, row.split())) for row in lst_in]

# Транспонируем таблицу: строки -> столбцы
columns = list(zip(*table))

# Перемешиваем столбцы с помощью shuffle
random.shuffle(columns)

# Обратно транспонируем: столбцы -> строки
shuffled_table = list(zip(*columns))

# Выводим результат в виде таблицы без пробелов в конце строк
for row in shuffled_table:
    print(' '.join(map(str, row)))
