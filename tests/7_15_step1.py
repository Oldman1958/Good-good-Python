from collections import deque


def find_chain_words(words, start_word, end_word, chain=None):
    # Если начальное или конечное слово не в списке, возвращаем пустой список
    if start_word not in words or end_word not in words:
        return []

    # Если слова одинаковые, возвращаем список с одним словом
    if start_word == end_word:
        return [start_word]

    # Множество посещённых слов
    visited = set()
    # Очередь для BFS: хранит пары (текущее слово, путь до него)
    queue = deque([(start_word, [start_word])])
    visited.add(start_word)

    while queue:
        current_word, path = queue.popleft()

        # Перебираем все слова из списка
        for word in words:
            # Пропускаем уже посещённые слова
            if word in visited:
                continue

            # Проверяем, отличается ли слово ровно на одну букву
            if count_differences(current_word, word) == 1:
                # Новый путь — текущий путь + новое слово
                new_path = path + [word]

                # Если достигли конечного слова, возвращаем путь
                if word == end_word:
                    return new_path

                # Добавляем слово в посещённые и в очередь
                visited.add(word)
                queue.append((word, new_path))

    # Если путь не найден, возвращаем пустой список
    return []


def count_differences(word1, word2):
    """Считает количество различающихся букв между двумя словами одинаковой длины."""
    return sum(1 for a, b in zip(word1, word2) if a != b)


