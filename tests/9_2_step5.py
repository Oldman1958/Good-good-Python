"""
Подвиг 3.
На вход программе подается натуральное число N (N > 8).
Необходимо его прочитать и объявить функцию-генератор, которая бы выдавала пароль длиной N символов из случайных букв,
цифр и некоторых других знаков.
Значение N передается в функцию-генератор первым аргументом.
Для получения последовательности допустимых символов для генерации паролей в программе импортированы две строки:
ascii_lowercase, ascii_uppercase (см. листинг ниже), на основе которых формируется общий список:

from string import ascii_lowercase, ascii_uppercase
chars = ascii_lowercase + ascii_uppercase + "0123456789!?@#$*"


Функция-генератор должна при каждом вызове возвращать новый пароль из случайно выбранных символов chars длиной N
и делать это бесконечно, то есть, вызывать ее можно бесконечное число раз.

Сгенерируйте с помощью функции-генератора первые пять паролей и выведите их в столбик (каждый с новой строки).

Подсказка: сгенерировать случайный индекс indx в диапазоне [a; b]
для выбора символа из chars можно с помощью функции randint модуля random:

import random
random.seed(1)
indx = random.randint(a, b)
"""

from string import ascii_lowercase, ascii_uppercase
import random

# Устанавливаем seed для воспроизводимости результатов (как в подсказке)
random.seed(1)

# Формируем строку допустимых символов
chars = ascii_lowercase + ascii_uppercase + "0123456789!?@#$*"

# Читаем входное число N
N = int(input())

# Объявляем функцию‑генератор для создания паролей
def password_generator(length):
    while True:  # Бесконечный цикл — генератор будет работать бесконечно
        # Создаём пароль: выбираем length случайных символов из chars
        password = ''.join(
            chars[random.randint(0, len(chars) - 1)]
            for _ in range(length)
        )
        yield password  # Возвращаем сгенерированный пароль и приостанавливаем выполнение

# Создаём экземпляр генератора для длины N
gen = password_generator(N)

# Генерируем и выводим первые пять паролей, каждый с новой строки
for _ in range(5):
    print(next(gen))


